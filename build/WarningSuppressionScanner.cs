using System.Text.RegularExpressions;

/// <summary>
/// Scans repository files for warning suppression mechanisms.
/// </summary>
static partial class WarningSuppressionScanner
{
    private static readonly string[] ExcludedDirectoryNames =
    [
        ".git",
        "artifacts",
        "bin",
        "node_modules",
        "obj",
        "TestResults",
    ];

    private static readonly HashSet<string> ExcludedRelativePaths = new(StringComparer.OrdinalIgnoreCase)
    {
        "tests/Build.Tests/WarningSuppressionApprovalValidatorTests.cs",
        "tests/Build.Tests/WarningSuppressionScannerTests.cs",
        "tests/Build.Tests/WarningSuppressionValidationTargetTests.cs",
    };

    private static readonly HashSet<string> ScannedExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".cs",
        ".csproj",
        ".editorconfig",
        ".fs",
        ".globalconfig",
        ".props",
        ".targets",
        ".vb",
    };

    private static readonly Dictionary<string, string> SuppressionPropertyDiagnosticIds = new(StringComparer.OrdinalIgnoreCase)
    {
        ["TreatWarningsAsErrors"] = "TreatWarningsAsErrors",
        ["SuppressTrimAnalysisWarnings"] = "SuppressTrimAnalysisWarnings",
        ["ErrorOnDuplicatePublishOutputFiles"] = "ErrorOnDuplicatePublishOutputFiles",
    };

    [GeneratedRegex(@"<(?<name>NoWarn|WarningsNotAsErrors)>\s*(?<value>.*?)\s*</\k<name>>", RegexOptions.IgnoreCase)]
    private static partial Regex DiagnosticListPropertyRegex();

    [GeneratedRegex(@"<(?<name>TreatWarningsAsErrors|SuppressTrimAnalysisWarnings|ErrorOnDuplicatePublishOutputFiles)>\s*(?<value>true|false)\s*</\k<name>>", RegexOptions.IgnoreCase)]
    private static partial Regex BooleanPropertyRegex();

    [GeneratedRegex(@"#pragma\s+warning\s+disable\s+(?<value>[^/\r\n]+)", RegexOptions.IgnoreCase)]
    private static partial Regex PragmaWarningDisableRegex();

    [GeneratedRegex(@"SuppressMessage\s*\(\s*""[^""]*""\s*,\s*""(?<diagnostic>[^""]+)""", RegexOptions.IgnoreCase)]
    private static partial Regex SuppressMessageRegex();

    [GeneratedRegex(@"dotnet_diagnostic\.(?<diagnostic>[A-Za-z]+\d+)\.severity\s*=\s*(?<severity>none|silent)", RegexOptions.IgnoreCase)]
    private static partial Regex EditorConfigSeverityRegex();

    [GeneratedRegex(@"^[A-Za-z]+\d+$")]
    private static partial Regex DiagnosticIdRegex();

    [GeneratedRegex(@"^\d+$")]
    private static partial Regex NumericDiagnosticRegex();

    public static IReadOnlyList<WarningSuppressionOccurrence> Scan(string repositoryRoot)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(repositoryRoot);

        var root = Path.GetFullPath(repositoryRoot);
        if (!Directory.Exists(root))
        {
            throw new DirectoryNotFoundException($"Repository root does not exist: {root}");
        }

        var occurrences = new List<WarningSuppressionOccurrence>();
        foreach (var path in Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
            .Where(path => ShouldScanFile(root, path)))
        {
            ScanFile(root, path, occurrences);
        }

        return occurrences
            .OrderBy(occurrence => occurrence.RelativePath, StringComparer.OrdinalIgnoreCase)
            .ThenBy(occurrence => occurrence.LineNumber)
            .ThenBy(occurrence => occurrence.Mechanism)
            .ThenBy(occurrence => occurrence.DiagnosticId, StringComparer.Ordinal)
            .ToArray();
    }

    private static bool ShouldScanFile(string root, string path)
    {
        var relativePath = Path.GetRelativePath(root, path);
        if (relativePath.StartsWith("..", StringComparison.Ordinal) || Path.IsPathRooted(relativePath))
        {
            return false;
        }

        var normalizedRelativePath = NormalizeRelativePath(relativePath);
        if (ExcludedRelativePaths.Contains(normalizedRelativePath))
        {
            return false;
        }

        var segments = relativePath.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        if (segments.Any(segment => ExcludedDirectoryNames.Contains(segment, StringComparer.OrdinalIgnoreCase)))
        {
            return false;
        }

        if (!ScannedExtensions.Contains(Path.GetExtension(path)))
        {
            return false;
        }

        return !IsAutoGeneratedFile(path);
    }

    private static bool IsAutoGeneratedFile(string path)
    {
        if (!Path.GetExtension(path).Equals(".cs", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        using var reader = File.OpenText(path);
        var firstLine = reader.ReadLine();
        return firstLine?.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) == true;
    }

    private static void ScanFile(string root, string path, List<WarningSuppressionOccurrence> occurrences)
    {
        var relativePath = NormalizeRelativePath(Path.GetRelativePath(root, path));
        var lines = File.ReadAllLines(path);

        for (var index = 0; index < lines.Length; index++)
        {
            var lineNumber = index + 1;
            var line = lines[index];
            ScanDiagnosticListProperty(relativePath, lineNumber, line, occurrences);
            ScanBooleanProperty(relativePath, lineNumber, line, occurrences);
            ScanPragmaWarningDisable(relativePath, lineNumber, line, occurrences);
            ScanSuppressMessage(relativePath, lineNumber, line, occurrences);
            ScanEditorConfigSeverity(relativePath, lineNumber, line, occurrences);
        }
    }

    private static void ScanDiagnosticListProperty(
        string relativePath,
        int lineNumber,
        string line,
        List<WarningSuppressionOccurrence> occurrences)
    {
        foreach (Match match in DiagnosticListPropertyRegex().Matches(line))
        {
            var mechanism = match.Groups["name"].Value.Equals("NoWarn", StringComparison.OrdinalIgnoreCase)
                ? WarningSuppressionMechanism.NoWarn
                : WarningSuppressionMechanism.WarningsNotAsErrors;

            foreach (var diagnosticId in SplitDiagnosticList(match.Groups["value"].Value))
            {
                AddOccurrence(relativePath, lineNumber, diagnosticId, mechanism, line, occurrences);
            }
        }
    }

    private static void ScanBooleanProperty(
        string relativePath,
        int lineNumber,
        string line,
        List<WarningSuppressionOccurrence> occurrences)
    {
        foreach (Match match in BooleanPropertyRegex().Matches(line))
        {
            var propertyName = match.Groups["name"].Value;
            var propertyValue = match.Groups["value"].Value;
            var mechanism = GetBooleanMechanism(propertyName, propertyValue);
            if (mechanism is null)
            {
                continue;
            }

            AddOccurrence(relativePath, lineNumber, propertyName, mechanism.Value, line, occurrences);
        }
    }

    private static WarningSuppressionMechanism? GetBooleanMechanism(string propertyName, string propertyValue)
    {
        if (propertyName.Equals("TreatWarningsAsErrors", StringComparison.OrdinalIgnoreCase) &&
            propertyValue.Equals("false", StringComparison.OrdinalIgnoreCase))
        {
            return WarningSuppressionMechanism.TreatWarningsAsErrorsFalse;
        }

        if (propertyName.Equals("SuppressTrimAnalysisWarnings", StringComparison.OrdinalIgnoreCase) &&
            propertyValue.Equals("true", StringComparison.OrdinalIgnoreCase))
        {
            return WarningSuppressionMechanism.SuppressTrimAnalysisWarnings;
        }

        if (propertyName.Equals("ErrorOnDuplicatePublishOutputFiles", StringComparison.OrdinalIgnoreCase) &&
            propertyValue.Equals("false", StringComparison.OrdinalIgnoreCase))
        {
            return WarningSuppressionMechanism.ErrorOnDuplicatePublishOutputFiles;
        }

        return null;
    }

    private static void ScanPragmaWarningDisable(
        string relativePath,
        int lineNumber,
        string line,
        List<WarningSuppressionOccurrence> occurrences)
    {
        var match = PragmaWarningDisableRegex().Match(line);
        if (!match.Success)
        {
            return;
        }

        foreach (var diagnosticId in SplitDiagnosticList(match.Groups["value"].Value))
        {
            AddOccurrence(relativePath, lineNumber, diagnosticId, WarningSuppressionMechanism.PragmaWarningDisable, line, occurrences);
        }
    }

    private static void ScanSuppressMessage(
        string relativePath,
        int lineNumber,
        string line,
        List<WarningSuppressionOccurrence> occurrences)
    {
        foreach (Match match in SuppressMessageRegex().Matches(line))
        {
            var diagnosticId = match.Groups["diagnostic"].Value.Split(':', 2)[0];
            AddOccurrence(relativePath, lineNumber, diagnosticId, WarningSuppressionMechanism.SuppressMessage, line, occurrences);
        }
    }

    private static void ScanEditorConfigSeverity(
        string relativePath,
        int lineNumber,
        string line,
        List<WarningSuppressionOccurrence> occurrences)
    {
        foreach (Match match in EditorConfigSeverityRegex().Matches(line))
        {
            AddOccurrence(
                relativePath,
                lineNumber,
                match.Groups["diagnostic"].Value,
                WarningSuppressionMechanism.EditorConfigSeverity,
                line,
                occurrences);
        }
    }

    private static IEnumerable<string> SplitDiagnosticList(string value)
    {
        return value
            .Split([',', ';', ' ', '\t'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Where(token => !token.StartsWith("$(", StringComparison.Ordinal))
            .Select(NormalizeDiagnosticId)
            .Where(diagnosticId => diagnosticId is not null)
            .Select(diagnosticId => diagnosticId!);
    }

    private static string? NormalizeDiagnosticId(string rawDiagnosticId)
    {
        var diagnosticId = rawDiagnosticId.Trim().TrimEnd(':').ToUpperInvariant();
        if (diagnosticId.Length == 0)
        {
            return null;
        }

        if (SuppressionPropertyDiagnosticIds.TryGetValue(diagnosticId, out var suppressionPropertyDiagnosticId))
        {
            return suppressionPropertyDiagnosticId;
        }

        var colonIndex = diagnosticId.IndexOf(':', StringComparison.Ordinal);
        if (colonIndex >= 0)
        {
            diagnosticId = diagnosticId[..colonIndex];
        }

        if (NumericDiagnosticRegex().IsMatch(diagnosticId))
        {
            return $"CS{int.Parse(diagnosticId):D4}";
        }

        return DiagnosticIdRegex().IsMatch(diagnosticId) ? diagnosticId : null;
    }

    private static void AddOccurrence(
        string relativePath,
        int lineNumber,
        string diagnosticId,
        WarningSuppressionMechanism mechanism,
        string sourceText,
        List<WarningSuppressionOccurrence> occurrences)
    {
        var normalizedDiagnosticId = NormalizeDiagnosticId(diagnosticId);
        if (normalizedDiagnosticId is null)
        {
            return;
        }

        occurrences.Add(new WarningSuppressionOccurrence(
            relativePath,
            lineNumber,
            normalizedDiagnosticId,
            mechanism,
            sourceText.Trim()));
    }

    private static string NormalizeRelativePath(string relativePath)
    {
        return relativePath.Replace(Path.DirectorySeparatorChar, '/').Replace(Path.AltDirectorySeparatorChar, '/');
    }
}

/// <summary>
/// Identifies the warning suppression mechanism found by <see cref="WarningSuppressionScanner" />.
/// </summary>
enum WarningSuppressionMechanism
{
    NoWarn,
    WarningsNotAsErrors,
    TreatWarningsAsErrorsFalse,
    SuppressTrimAnalysisWarnings,
    ErrorOnDuplicatePublishOutputFiles,
    PragmaWarningDisable,
    SuppressMessage,
    EditorConfigSeverity,
}

/// <summary>
/// A warning suppression occurrence with normalized diagnostic identity and source location.
/// </summary>
sealed record WarningSuppressionOccurrence(
    string RelativePath,
    int LineNumber,
    string DiagnosticId,
    WarningSuppressionMechanism Mechanism,
    string SourceText);
