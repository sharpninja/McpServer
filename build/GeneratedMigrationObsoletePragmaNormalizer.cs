/// <summary>
/// TR-MCP-QUALITY-001 ac-23 / TEST-MCP-AIUNIT-002 ac-6 / W18: opt-in mechanical
/// replacement of exact generated-migration CS0612/CS0618 pragma pairs.
/// </summary>
public static class GeneratedMigrationObsoletePragmaNormalizer
{
    private const string PragmaToken = "#pragma";

    private static readonly string DisablePair = PragmaToken + " warning disable " + "612, 618";

    private static readonly string RestorePair = PragmaToken + " warning restore " + "612, 618";

    private static readonly string[] MigrationRoots =
    [
        "src/McpServer.Storage/Migrations",
        "src/McpServer.Storage.SqliteMigrations",
        "src/McpServer.Storage.SqlServerMigrations",
        "src/McpServer.Storage.PostgreSqlMigrations",
    ];

    /// <summary>
    /// Replaces exact disable/restore 612, 618 pairs with blank lines in eligible
    /// generated migration files. Invokes <paramref name="write"/> only when content changes.
    /// </summary>
    /// <param name="catalog">Candidate paths supplied by the caller (mock or filesystem).</param>
    /// <param name="read">Reads current file text.</param>
    /// <param name="write">Writes replacement text. Captured by tests; atomic on disk in the Nuke target.</param>
    public static void Normalize(
        IReadOnlyList<string> catalog,
        Func<string, string> read,
        Action<string, string> write)
    {
        ArgumentNullException.ThrowIfNull(catalog);
        ArgumentNullException.ThrowIfNull(read);
        ArgumentNullException.ThrowIfNull(write);

        foreach (var path in catalog)
        {
            if (!IsEligiblePath(path))
            {
                continue;
            }

            var original = read(path);
            if (!TryNormalizeContent(original, out var normalized))
            {
                continue;
            }

            write(path, normalized);
        }
    }

    /// <summary>
    /// Read-only scan of the four migration roots under <paramref name="repositoryRoot"/>.
    /// Does not write files.
    /// </summary>
    /// <param name="repositoryRoot">Repository or fixture root.</param>
    /// <returns>Relative path and line number of each exact pragma pair.</returns>
    public static IReadOnlyList<(string RelativePath, int LineNumber)> ScanRepository(string repositoryRoot)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(repositoryRoot);

        var root = Path.GetFullPath(repositoryRoot);
        var hits = new List<(string RelativePath, int LineNumber)>();
        foreach (var relativeRoot in MigrationRoots)
        {
            var absoluteRoot = Path.Combine(root, relativeRoot.Replace('/', Path.DirectorySeparatorChar));
            if (!Directory.Exists(absoluteRoot))
            {
                continue;
            }

            foreach (var file in Directory.EnumerateFiles(absoluteRoot, "*.cs", SearchOption.AllDirectories))
            {
                var relativePath = NormalizeRelativePath(Path.GetRelativePath(root, file));
                if (!IsEligiblePath(relativePath))
                {
                    continue;
                }

                var text = File.ReadAllText(file);
                foreach (var lineNumber in EnumerateExactPairLineNumbers(text))
                {
                    hits.Add((relativePath, lineNumber));
                }
            }
        }

        return hits;
    }

    private static bool TryNormalizeContent(string original, out string normalized)
    {
        normalized = original;
        if (!IsAutoGenerated(original))
        {
            return false;
        }

        var newline = original.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var lines = original.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
        var changed = false;
        for (var i = 0; i < lines.Length; i++)
        {
            if (!IsExactPairLine(lines[i]))
            {
                continue;
            }

            lines[i] = string.Empty;
            changed = true;
        }

        if (!changed)
        {
            return false;
        }

        normalized = string.Join(newline, lines);
        return true;
    }

    private static IEnumerable<int> EnumerateExactPairLineNumbers(string text)
    {
        if (!IsAutoGenerated(text))
        {
            yield break;
        }

        var lines = text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
        for (var i = 0; i < lines.Length; i++)
        {
            if (IsExactPairLine(lines[i]))
            {
                yield return i + 1;
            }
        }
    }

    private static bool IsEligiblePath(string path)
    {
        var normalized = NormalizeRelativePath(path);
        var fileName = Path.GetFileName(normalized.Replace('/', Path.DirectorySeparatorChar));
        var nameOk = fileName.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.Equals("McpDbContextModelSnapshot.cs", StringComparison.OrdinalIgnoreCase);
        if (!nameOk)
        {
            return false;
        }

        foreach (var root in MigrationRoots)
        {
            if (normalized.Equals(root, StringComparison.OrdinalIgnoreCase)
                || normalized.StartsWith(root + "/", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsAutoGenerated(string text)
    {
        var newline = text.IndexOf('\n');
        var firstLine = newline < 0 ? text : text[..newline];
        firstLine = firstLine.TrimEnd('\r');
        return firstLine.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsExactPairLine(string line)
    {
        var trimmed = line.Trim();
        return trimmed.Equals(DisablePair, StringComparison.Ordinal)
            || trimmed.Equals(RestorePair, StringComparison.Ordinal);
    }

    private static string NormalizeRelativePath(string path)
    {
        return path.Replace('\\', '/');
    }
}
